[[keyboard.bindings]]
key = "4"
mods = "Control|Shift"
chars = "\u001b[52;6u"

[[keyboard.bindings]]
key = "5"
mods = "Control|Shift"
chars = "\u001b[53;6u"

[[keyboard.bindings]]
key = "6"
mods = "Control|Shift"
chars = "\u001b[54;6u"

[[keyboard.bindings]]
key = "7"
mods = "Control|Shift"
chars = "\u001b[55;6u"

[[keyboard.bindings]]
key = "8"
mods = "Control|Shift"
chars = "\u001b[56;6u"

