}

# --- E. Termux ---
configure_termux() {
    echo -e "\n[*] Configuring Termux (Android)..."
    local termux_dir="$HOME/.termux"
    local config_file="$termux_dir/termux.properties"

    mkdir -p "$termux_dir"
    [ -f "$config_file" ] && cp -f "$config_file" "$config_file.backup"

    local start_marker="# >>> KRS NEOVIM TERMUX SHORTCUTS >>>"
    local end_marker="# <<< KRS NEOVIM TERMUX SHORTCUTS <<<"

    if [ -f "$config_file" ]; then
        sed -i "/$start_marker/,/$end_marker/d" "$config_file"
    fi

    cat >> "$config_file" << 'EOF'
# >>> KRS NEOVIM TERMUX SHORTCUTS >>>
# Quick-access extra keys for KRS Neovim Environments and Navigation
extra-keys = [ \
  ['ESC', 'CTRL', 'ALT', 'TAB', 'SHIFT', 'UP', 'DOWN'], \
  [{macro: "\033[69;6u", display: "ENV"}, {macro: "\033[49;6u", display: "E1"}, {macro: "\033[50;6u", display: "E2"}, {macro: "\033[51;6u", display: "E3"}, 'LEFT', 'RIGHT', 'ENTER'] \
]
ctrl-space-workaround = true
shortcut.create-session = false
# <<< KRS NEOVIM TERMUX SHORTCUTS <<<
EOF
    echo -e "   ${COLOR_GREEN}[+] Termux configuration written to $config_file${COLOR_NC}"
    echo -e "   ${COLOR_CYAN}[i] Run 'termux-reload-settings' inside Termux to reload configuration.${COLOR_NC}"
}

# --- F. Windows Terminal (WSL / Git Bash bridge) ---
configure_winter() {
    echo -e "\n[*] Windows Terminal detected. Triggering PowerShell setup bridge..."
    if command -v powershell.exe >/dev/null 2>&1; then
        local script_dir="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
        powershell.exe -NoProfile -ExecutionPolicy Bypass -File "$script_dir/setup-powershell.ps1"
    else
        echo -e "   ${COLOR_YELLOW}[!] powershell.exe not available in current PATH.${COLOR_NC}"
    fi
}

# ------------------------------------------------------------------------------
# 3. Execution Dispatch
# ------------------------------------------------------------------------------
if [ "$CONFIG_ALL" = true ]; then
    echo -e "\n${COLOR_YELLOW}[*] Configuring ALL supported terminals on system...${COLOR_NC}"
    configure_kitty
    configure_foot
    configure_wezterm
    configure_alacritty
    configure_termux
    [ "$ACTIVE_TERM" = "winter" ] && configure_winter
elif [ -n "$TARGET_TERM" ]; then
    case "$TARGET_TERM" in
        kitty) configure_kitty ;;
        foot) configure_foot ;;
        wezterm) configure_wezterm ;;
        alacritty) configure_alacritty ;;
        termux) configure_termux ;;
        winter|wt) configure_winter ;;
        *) echo -e "${COLOR_RED}Unknown terminal '$TARGET_TERM'. Choose: kitty, foot, wezterm, alacritty, termux, winter.${COLOR_NC}" ;;
    esac
else
    case "$ACTIVE_TERM" in
        kitty) configure_kitty ;;
        foot) configure_foot ;;
        wezterm) configure_wezterm ;;
        alacritty) configure_alacritty ;;
        termux) configure_termux ;;
        winter) configure_winter ;;
        *)
            echo -e "${COLOR_YELLOW}[*] Configuring default desktop terminal configs (Kitty, WezTerm, Alacritty)...${COLOR_NC}"
            configure_kitty
            configure_wezterm
            configure_alacritty
            ;;
    esac
fi

echo -e "\n${COLOR_GREEN}============================================================${COLOR_NC}"
echo -e "${COLOR_GREEN} [OK] Cross-terminal keybindings configured successfully!   ${COLOR_NC}"
echo -e "${COLOR_GREEN}============================================================${COLOR_NC}"
echo -e "Restart your terminal emulator or reload its configuration to apply."
